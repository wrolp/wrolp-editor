const TABLES: Record<Lang, Table> = { en: EN, zh: ZH };

/**
 * Languages offered in Settings. Labels stay in their own language on purpose, and the
 * value must be a key of TABLES plus a field of the backend's Settings.language.
 */
export const LANGUAGES: { value: Lang; label: string }[] = [
  { value: "en", label: "English" },
  { value: "zh", label: "中文" },
];

let current: Lang = "en";

export function setLang(lang: string): void {
  current = lang in TABLES ? (lang as Lang) : "en";
}

export function getLang(): Lang {
  return current;
}

type Params = Record<string, string | number>;

function fill(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in params ? String(params[key]) : whole
  );
}

export function t(key: string, params?: Params): string {
  const table = TABLES[current];
  const text = table[key] ?? EN[key];
  if (text === undefined) {
    // A key missing from every table would otherwise render as itself in the UI.
    if (import.meta.env.DEV) console.warn(`i18n: missing key "${key}"`);
    return fill(key, params);
  }
  return fill(text, params);
}

/** Turn a backend error ("code" or "code:detail") into localized text. */
export function translateError(raw: string): string {
  const colon = raw.indexOf(":");
  const code = colon < 0 ? raw : raw.slice(0, colon);
  const detail = colon < 0 ? "" : raw.slice(colon + 1).trim();
  const template = TABLES[current][`err.${code}`] ?? EN[`err.${code}`];
  if (!template) return raw;
  return fill(template, { detail });
}

/**
 * An ISO-8601 instant as `yyyy-MM-dd HH:mm:ss` in the reader's own timezone.
 *
 * The stored value stays the UTC string it was written as — this is only how it is shown. The
 * parts are padded by hand instead of going through `toLocaleString`, so the separators and the
 * field widths do not change with the UI language and a version list stays scannable by eye. The
 * row keeps the ISO string as its title for anybody who wants to be sure.
 */
export function formatWhen(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  const two = (n: number) => String(n).padStart(2, "0");
  return `${date.getFullYear()}-${two(date.getMonth() + 1)}-${two(date.getDate())} ${two(
    date.getHours(),
  )}:${two(date.getMinutes())}:${two(date.getSeconds())}`;
}

/**
 * Just the time of day, for a row too narrow to hold the whole date.
 *
 * A commit row in the sidebar spends its width on the graph, the subject and the names on the
 * tip; the date is the part that can step aside, and the full timestamp stays in the row's
 * tooltip either way.
 */
export function formatClock(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  const two = (n: number) => String(n).padStart(2, "0");
  return `${two(date.getHours())}:${two(date.getMinutes())}`;
}
